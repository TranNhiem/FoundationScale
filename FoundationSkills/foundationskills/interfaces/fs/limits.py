"""README "Honest limits" generated from a probe record (A5.3), never hand-written.

Each row is derived from one measured probe field. A field the probe did not measure yields an
UNMEASURED row that says how to measure it; nothing is inferred. The README section between
``BEGIN``/``END`` is rewritten from a committed probe record by ``fskills limits --write``, and a
conformance test regenerates it so the text cannot drift from the record.
"""

from __future__ import annotations

from collections.abc import Mapping
from pathlib import Path
from typing import Any

BEGIN = "<!-- limits:begin (generated by `fskills limits --write`; do not edit by hand) -->"
END = "<!-- limits:end -->"


def _key(caps: Mapping[str, Any], name: str) -> Mapping[str, Any]:
    return (caps.get("probe_keys") or {}).get(name) or {
        "status": "unmeasured",
        "value": None,
        "reason": "key absent from this probe record",
    }


def limit_rows(caps: Mapping[str, Any]) -> list[str]:
    """One sentence per limit, each traceable to the probe field it came from."""
    rows: list[str] = []
    kinds = caps.get("rl_reward_kinds")
    if kinds:
        rows.append(
            f"RL (`rl` plane) verifies only these reward kinds: {', '.join(kinds)} "
            "(`rl_reward_kinds`); `agentic_rl` rewards are measured in its own runtime probe"
        )
    else:
        rows.append("RL reward kinds: UNMEASURED (`rl_reward_kinds` empty in this record)")

    lora = caps.get("rl_adapter_support")
    rows.append(
        {
            True: "RL trains LoRA adapters (`rl_adapter_support`)",
            False: "RL has no LoRA support: it trains the full model (`rl_adapter_support`)",
            None: "RL LoRA support: UNMEASURED (`rl_adapter_support`)",
        }[lora]
    )

    pref = caps.get("pref_saves_checkpoint")
    rows.append(
        {
            True: "the preference trainer saves its checkpoint (`pref_saves_checkpoint`)",
            False: "the preference trainer saves no checkpoint (`pref_saves_checkpoint`)",
            None: "preference checkpoint saving: UNMEASURED (`pref_saves_checkpoint`)",
        }[pref]
    )

    mask = _key(caps, "sft_assistant_label_mask")
    if mask["status"] == "measured":
        rows.append(
            "SFT supervises assistant tokens only (behavioural check of `assistant_label_mask`)"
            if (mask["value"] or {}).get("assistant_only")
            else "SFT label mask failed its behavioural check: assistant-only loss is NOT verified"
        )
    else:
        rows.append(f"SFT loss masking: UNMEASURED ({mask['reason']})")

    refused = list(caps.get("refused_axes") or [])
    if caps.get("axes_measured"):
        rows.append(
            f"the FS trainer refuses {'/'.join(a.upper() for a in refused)} "
            "(deep probe; does not cover the Megatron-Bridge lane)"
            if refused
            else "the FS trainer refuses no parallel axis (deep probe)"
        )
    else:
        rows.append("parallel axes (TP/PP/EP/CP): UNMEASURED (run `fskills probe --deep`)")

    mega = _key(caps, "megatron_bridge")
    value = mega.get("value") or {}
    if mega["status"] != "measured":
        rows.append(f"Megatron: UNMEASURED ({mega['reason']})")
    elif "megatron" in (caps.get("backends") or []):
        rows.append(
            "a Megatron backend is usable: FS lane plus megatron.core importable "
            "(`megatron_bridge`)"
        )
    elif value.get("fs_lane"):
        rows.append(
            "FS ships a Megatron-Bridge lane, but this environment cannot run it "
            f"({mega['reason'] or 'megatron.core missing'}; `megatron_bridge`); "
            "FS's own trainer has no Megatron backend"
        )
    else:
        rows.append("there is no Megatron backend (`megatron_bridge`)")

    speech = _key(caps, "speech")
    if speech["status"] != "measured":
        rows.append(f"speech: UNMEASURED ({speech['reason']})")
    elif not (speech["value"] or {}).get("audio_decode"):
        rows.append(f"speech: modules present, audio decode unavailable here ({speech['reason']})")

    video = _key(caps, "video_frame_budget")
    if video["status"] != "measured":
        rows.append(f"video: UNMEASURED ({video['reason']})")
    else:
        backends = ", ".join((video["value"] or {}).get("decode_backends") or []) or "none"
        rows.append(
            f"video: decode backends {backends}; no measured frame envelope, so a frame count "
            "beyond a measured run is UNMEASURED (`video_frame_budget`)"
        )
    return rows


def render(caps: Mapping[str, Any], source: str) -> str:
    """The README block, markers included."""
    body = "\n".join(f"  - {row};" for row in limit_rows(caps))
    body = body[:-1] + "."
    commit = caps.get("fs_version") or "unknown"
    return (
        f"{BEGIN}\n  Generated from `{source}` (FoundationScale {commit}); "
        f"regenerate with `fskills limits --probe-json {source} --write README.md`.\n{body}\n{END}"
    )


def replace_section(text: str, block: str) -> str:
    """Swap the marked section of ``text`` for ``block``; refuses when the markers are missing."""
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < start:
        raise ValueError(f"limits markers not found (expected {BEGIN!r} ... {END!r})")
    return text[:start] + block + text[end + len(END) :]


def write_readme(readme: Path, caps: Mapping[str, Any], source: str) -> bool:
    """Rewrite the section in place; True when the file changed."""
    old = readme.read_text(encoding="utf-8")
    new = replace_section(old, render(caps, source))
    if new != old:
        readme.write_text(new, encoding="utf-8")
    return new != old
