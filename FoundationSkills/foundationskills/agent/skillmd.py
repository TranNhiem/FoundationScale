"""Generated usage blocks for SKILL.md.

The generated usage block keeps SKILL.md in lockstep with the CLI and the declared
rules (atlas C13 skill rot). Nothing here is derived from introspection of prose:
it is pure text over an argparse parser and a skill, and no file is written except
through ``write_block``.
"""
from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path

from foundationskills.core.status import Status

BEGIN = "<!-- FS-USAGE:BEGIN (generated by `fskills skillmd build`; do not edit) -->"
END = "<!-- FS-USAGE:END -->"
EXIT_CODES = {"PASS": 0, "RED": 5, "UNMEASURED": 95, "REFUSED": 96}
assert {s.value: s.exit_code for s in Status} == EXIT_CODES, "EXIT_CODES drifted from core.status"


def cli_path(skill) -> list[str] | None:
    """The CLI words after "fskills" in skill.fs_interface.entries; None when absent."""
    return next((e.split()[1:] for e in skill.fs_interface.entries if e.split()[:1] == ["fskills"]), None)


def subparser_for(parser: argparse.ArgumentParser, path: list[str]) -> argparse.ArgumentParser | None:
    """Walk _SubParsersAction choices along PATH from PARSER (None on an unknown word)."""
    current = parser
    for word in list(path or []):
        current = next((a.choices.get(word) for a in getattr(current, "_actions", ())
                        if isinstance(a, argparse._SubParsersAction) and word in a.choices), None)
        if current is None:
            return None
    return current


def _flags(parser) -> list[dict]:
    """Optional flags (positionals and -h/--help skipped) as dicts, sorted by long name."""
    rows = []
    for act in getattr(parser, "_actions", ()):
        if not act.option_strings or act.dest == "help":
            continue
        long = next((s for s in act.option_strings if s.startswith("--")), act.option_strings[0])
        ch, dflt = getattr(act, "choices", None), getattr(act, "default", None)
        rows.append({"long": long, "required": bool(getattr(act, "required", False)),
                     "choices": list(ch) if ch else None,
                     "default": dflt if dflt is None or dflt is argparse.SUPPRESS else repr(dflt)})
    return sorted(rows, key=lambda f: f["long"])


def iter_commands(parser, path) -> list[dict]:
    """One {"verb", "flags"} row per subcommand of the CLI path, else one for the command."""
    path = list(path or [])
    target = subparser_for(parser, path) if path else None
    if target is None:
        return []
    subs = {n: s for a in getattr(target, "_actions", ()) if isinstance(a, argparse._SubParsersAction)
            for n, s in a.choices.items()}
    rows = ([{"verb": "fskills " + " ".join([*path, n]), "flags": _flags(s)} for n, s in subs.items()]
            if subs else [{"verb": "fskills " + " ".join(path), "flags": _flags(target)}])
    return sorted(rows, key=lambda c: c["verb"])


def usage_model(skill, parser) -> dict:
    """The dict render_block renders: name, commands, rules, artifacts, exit codes."""
    path = cli_path(skill)
    rules = [{"rule_id": r.rule_id, "severity": str(getattr(r.severity, "value", r.severity)),
              "phase": r.phase, "description": r.description} for r in sorted(skill.rules, key=lambda r: r.rule_id)]
    return {"name": skill.name, "commands": iter_commands(parser, path) if path else [], "rules": rules,
            "artifacts": sorted(skill.produces), "exit_codes": EXIT_CODES}


def _cell(value) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def _flag_text(flag: dict) -> str:
    bits = ["required"] if flag.get("required") else []
    bits += ["choices {" + ",".join(_cell(c) for c in flag["choices"]) + "}"] if flag.get("choices") else []
    bits += ["default " + str(flag["default"])] if flag.get("default") is not None else []
    return " (" + "; ".join(bits) + ")" if bits else ""


def render_block(model: dict) -> str:
    """Deterministic markdown between BEGIN and END: same model -> byte-identical text."""
    lines = [BEGIN, "## Usage (generated)"]
    commands = model.get("commands") or []
    if not commands:
        lines.append("- (no CLI entry)")
    for cmd in commands:
        lines.append(f"- `{cmd['verb']}`")
        lines += [f"  - `{f['long']}`{_flag_text(f)}" for f in cmd.get("flags") or []]
    lines += ["", "### Rules", "", "| Rule | Phase | Severity | Description |", "| --- | --- | --- | --- |"]
    for rule in model.get("rules") or []:
        lines.append("| " + " | ".join(_cell(rule[k])
                                       for k in ("rule_id", "phase", "severity", "description")) + " |")
    lines += ["", "### Artifacts", ", ".join(_cell(a) for a in model.get("artifacts") or []) or "none"]
    codes = model.get("exit_codes") or EXIT_CODES
    lines += ["", "### Exit codes", " · ".join(f"{k} {codes[k]}" for k in EXIT_CODES), END]
    return "\n".join(lines) + "\n"


def block_sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _locate(text: str):
    """(start of BEGIN, end of END, end of its trailing newlines); None when there are no markers."""
    begins = [m.start() for m in re.finditer(re.escape(BEGIN), text)]
    ends = [m.start() for m in re.finditer(re.escape(END), text)]
    if not begins and not ends:
        return None
    if len(begins) != 1 or len(ends) != 1 or ends[0] < begins[0]:
        raise ValueError("FS-USAGE markers are unbalanced or duplicated in SKILL.md")
    after_end = ends[0] + len(END)
    rest = text[after_end:]
    return begins[0], after_end, after_end + len(rest) - len(rest.lstrip("\n"))


def extract_block(skill_md: str) -> str | None:
    """BEGIN..END inclusive plus one trailing newline, or None when the block is absent."""
    loc = _locate(skill_md)
    return None if loc is None else skill_md[loc[0]:loc[2]].rstrip("\n") + "\n"


def replace_block(skill_md: str, block: str) -> str:
    """Replace the block, else insert it before the first "## Validation rules" line, else append."""
    body, loc = block.rstrip("\n"), _locate(skill_md)
    if loc is not None:
        tail = skill_md[loc[1]:]
        return skill_md[:loc[0]] + body + (tail if tail[:1] == "\n" else "\n" + tail)
    idx = next((m.start() for m in re.finditer(r"^## Validation rules", skill_md, re.M)), len(skill_md))
    chunks = (skill_md[:idx].rstrip("\n"), body, skill_md[idx:].lstrip("\n"))
    return "\n\n".join(c for c in chunks if c).rstrip("\n") + "\n"


def check(skill, parser, skill_md: str) -> list[str]:
    """[] when the generated block is fresh, else the one problem to report."""
    current = extract_block(skill_md)
    if current is None:
        return ["missing generated usage block"]
    expected = render_block(usage_model(skill, parser))
    return [] if current == expected else ["generated usage block is stale"]


def write_block(path, text: str) -> Path:
    """Write TEXT (a usage block or a whole SKILL.md) to PATH: the only writer in this module."""
    target = Path(path)
    target.write_text(text, encoding="utf-8")
    return target
